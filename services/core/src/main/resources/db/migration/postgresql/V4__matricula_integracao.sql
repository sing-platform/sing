-- Pendencia da matricula criada (N2).
--
-- A matricula e esta linha nascem na mesma transacao. O event_id nao muda
-- em retry. Publicar no RabbitMQ e chamar o finance acontecem depois do commit,
-- cada um com o proprio status. O claim (claimed_by + claim_ate) evita que
-- as tres replicas do core trabalhem a mesma linha ao mesmo tempo.

CREATE TABLE matricula_integracao (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id            BIGINT NOT NULL,
    event_id                VARCHAR(36) NOT NULL,
    envelope                TEXT NOT NULL,
    valor_centavos          INTEGER NOT NULL,
    vencimento              DATE NOT NULL,
    publicacao              VARCHAR(20) NOT NULL,
    cobranca                VARCHAR(20) NOT NULL,
    tentativas_publicacao   INTEGER NOT NULL DEFAULT 0,
    tentativas_cobranca     INTEGER NOT NULL DEFAULT 0,
    proxima_publicacao      TIMESTAMP(3) NULL,
    proxima_cobranca        TIMESTAMP(3) NULL,
    claimed_by              VARCHAR(120) NULL,
    claim_ate               TIMESTAMP(3) NULL,
    cobranca_id             BIGINT NULL,
    criado_em               TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_matricula_integracao_matricula UNIQUE (matricula_id),
    CONSTRAINT uq_matricula_integracao_event UNIQUE (event_id),
    CONSTRAINT fk_matricula_integracao_enrollment FOREIGN KEY (matricula_id) REFERENCES enrollment (id)
);
