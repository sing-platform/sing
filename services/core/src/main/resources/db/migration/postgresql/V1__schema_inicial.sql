-- SGS-CADI core — schema inicial (PostgreSQL)
--
-- Squash das migrations V1..V10 do monolito original (dialetos h2 + sqlserver).
-- O banco nasce vazio neste repositorio, entao nao ha historico a preservar.
--
-- Diferencas deliberadas em relacao ao original:
--   * a tabela de usuarios ja nasce como `users` (no monolito era `user`,
--     renomeada na V3). `user` e palavra reservada no PostgreSQL.
--   * colunas adicionadas por ALTER TABLE nas V6/V10 ja vem na definicao.
--   * as 3 stored procedures da V5 (SQL Server) NAO foram portadas: os
--     relatorios passam a usar SQL portavel unico. Ver docs/adr.
--   * sem triggers de auditoria: a auditoria passa a ser por evento de dominio.
