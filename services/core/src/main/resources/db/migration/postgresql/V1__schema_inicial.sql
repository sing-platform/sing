-- ---------------------------------------------------------- DOCUMENTS -------
-- Precede `attendance`: a justificativa de falta referencia um documento.

CREATE TABLE user_documents (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_person_id      BIGINT NOT NULL,
    file_name            VARCHAR(255) NOT NULL,
    original_file_name   VARCHAR(255) NOT NULL,
    mime_type            VARCHAR(100) NOT NULL,
    file_size            BIGINT NOT NULL,
    category             VARCHAR(30) NOT NULL,
    scope                VARCHAR(30) NOT NULL,
    storage_key          VARCHAR(512) NOT NULL,
    uploaded_by_user_id  BIGINT NOT NULL,
    uploaded_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    description          VARCHAR(500) NULL,
    active               BOOLEAN NOT NULL DEFAULT TRUE,
    -- V6: fluxo de aprovacao de atestado
    status               VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    reference_date_start DATE NULL,
    reference_date_end   DATE NULL,
    reviewed_by_user_id  BIGINT NULL,
    reviewed_at          TIMESTAMP WITH TIME ZONE NULL,
    rejection_reason     VARCHAR(500) NULL,
    CONSTRAINT fk_user_doc_owner    FOREIGN KEY (owner_person_id)     REFERENCES person (id),
    CONSTRAINT fk_user_doc_uploader FOREIGN KEY (uploaded_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_user_doc_reviewer FOREIGN KEY (reviewed_by_user_id) REFERENCES users (id)
);

