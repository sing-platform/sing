-- ---------------------------------------------------------------- IAM -------

CREATE TABLE role (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    created_at      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    deactivated_by  BIGINT NULL,
    deactivated_at  TIMESTAMP(3) NULL,
    CONSTRAINT uq_role_name UNIQUE (name)
);

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(255) NOT NULL,
    password        VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    role_id         BIGINT NOT NULL,
    created_at      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    deactivated_by  BIGINT NULL,
    deactivated_at  TIMESTAMP(3) NULL,
    CONSTRAINT uq_user_username UNIQUE (username),
    CONSTRAINT uq_user_email UNIQUE (email),
    CONSTRAINT fk_user_role FOREIGN KEY (role_id) REFERENCES role (id)
);

-- ------------------------------------------------------------- PEOPLE -------

CREATE TABLE address (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zip_code        VARCHAR(10) NOT NULL,
    street          VARCHAR(255) NOT NULL,
    number          INT NOT NULL,
    complement      VARCHAR(255) NULL,
    neighborhood    VARCHAR(255) NOT NULL,
    city            VARCHAR(255) NOT NULL,
    state           VARCHAR(25) NOT NULL,
    created_at      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    deactivated_by  BIGINT NULL,
    deactivated_at  TIMESTAMP(3) NULL
);

CREATE TABLE person (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    cpf             VARCHAR(14) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    phone           VARCHAR(20) NOT NULL,
    birth_date      DATE NOT NULL,
    address_id      BIGINT NOT NULL,
    user_id         BIGINT NOT NULL,
    created_at      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    deactivated_by  BIGINT NULL,
    deactivated_at  TIMESTAMP(3) NULL,
    CONSTRAINT uq_person_cpf UNIQUE (cpf),
    CONSTRAINT uq_person_email UNIQUE (email),
    CONSTRAINT fk_person_address FOREIGN KEY (address_id) REFERENCES address (id),
    CONSTRAINT fk_person_user FOREIGN KEY (user_id) REFERENCES users (id)
);

